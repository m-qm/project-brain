import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "files");
const out = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "content.generated.ts");

function walk(dir, base = dir) {
  const entries = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) {
      entries.push(...walk(full, base));
    } else {
      entries.push(relative(base, full).replace(/\\/g, "/"));
    }
  }
  return entries;
}

const files = walk(root);
const lines = [
  "// Auto generated by scripts/embed-files.mjs — do not edit",
  "export const TEMPLATE_CONTENT: Record<string, string> = {",
];
for (const rel of files.sort()) {
  const text = readFileSync(join(root, rel), "utf8");
  const escaped = JSON.stringify(text);
  lines.push(`  ${JSON.stringify(rel)}: ${escaped},`);
}
lines.push("};");
writeFileSync(out, lines.join("\n") + "\n");
console.log(`Embedded ${files.length} templates`);
